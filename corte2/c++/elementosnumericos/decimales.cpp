#include <iostream> // Incluye la librería para mostrar datos en consola.
using namespace std; // Permite usar cout y endl directamente.

int main() { // Inicia la función principal.
    double temperatura = 24.5; // Declara una variable decimal para una temperatura.
    double distancia = 1.75;   // Declara una variable decimal para una distancia.
    double voltaje = 3.3;      // Declara una variable decimal para un voltaje.
    
    cout << temperatura << endl; // Muestra la temperatura.
    cout << distancia << endl;   // Muestra la distancia.
    cout << voltaje << endl;     // Muestra el voltaje.
    return 0; // Termina el programa correctamente.
}

